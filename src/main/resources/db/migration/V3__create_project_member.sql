CREATE TABLE public.project_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    project_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    role VARCHAR(20) NOT NULL,
    joined_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,

    CONSTRAINT project_member_pkey
        PRIMARY KEY (id),

    CONSTRAINT fk_project_member_user
        FOREIGN KEY (user_id) REFERENCES public.users(id),

    CONSTRAINT fk_project_member_project
        FOREIGN KEY (project_id) REFERENCES public.projects(id),

    CONSTRAINT uk_project_member_project_user
        UNIQUE (project_id, user_id),

    CONSTRAINT project_member_roles_check
         CHECK (role IN ('OWNER', 'ADMIN', 'MEMBER'))
);

INSERT INTO public.project_members(project_id, user_id, role, joined_at)
SELECT p.id, p.user_id, 'OWNER', CURRENT_TIMESTAMP
FROM public.projects p;
