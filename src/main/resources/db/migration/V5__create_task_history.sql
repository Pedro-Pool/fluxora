CREATE TABLE public.task_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    action VARCHAR(20) NOT NULL,
    field_name VARCHAR(100),
    old_value TEXT,
    new_value TEXT,
    created_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_task_history_task
                 FOREIGN KEY (task_id)
                 REFERENCES public.tasks(id)
                 ON DELETE CASCADE,

    CONSTRAINT fk_task_history_user
                 FOREIGN KEY (user_id)
                 REFERENCES public.users(id),

    CONSTRAINT chk_task_history_action
                 CHECK (
                     action IN (
                     'CREATED',
                     'UPDATED',
                     'COMPLETED',
                     'REOPENED',
                     'CANCELED',
                     'ASSIGNED'
                     )
                 )
);

CREATE INDEX idx_tak_history_task_id
    ON public.task_history(task_id);

CREATE INDEX idx_task_history_user_id
    ON public.task_history(user_id);

CREATE INDEX idx_task_history_created_at
    ON public.task_history(created_at);