
CREATE TABLE public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    create_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    email VARCHAR(254) NOT NULL,
    name VARCHAR(100) NOT NULL,
    password_hash VARCHAR(60) NOT NULL,

    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    description VARCHAR(1000),
    name VARCHAR(100) NOT NULL,
    user_id BIGINT NOT NULL,

    CONSTRAINT projects_pkey PRIMARY KEY (id),

    CONSTRAINT fk_projects_user
     FOREIGN KEY (user_id) REFERENCES public.users(id)
);

CREATE TABLE public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name VARCHAR(50) NOT NULL,
    user_id BIGINT NOT NULL,

    CONSTRAINT categories_pkey PRIMARY KEY (id),
    CONSTRAINT uk_category_name_user UNIQUE (user_id, name),
    CONSTRAINT fk_categories_user
       FOREIGN KEY (user_id) REFERENCES public.users(id)
);

CREATE TABLE public.tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    description VARCHAR(1000),
    title VARCHAR(150) NOT NULL,
    project_id BIGINT NOT NULL,
    due_date DATE,
    priority VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    update_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    completed_at TIMESTAMP(6) WITHOUT TIME ZONE,

    CONSTRAINT tasks_pkey PRIMARY KEY (id),
    CONSTRAINT tasks_priority_check
      CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),

    CONSTRAINT tasks_status_check
      CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE')),

    CONSTRAINT fk_tasks_project
      FOREIGN KEY (project_id) REFERENCES public.projects(id)
);

CREATE TABLE public.task_categories (
    task_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,

    CONSTRAINT task_categories_pkey PRIMARY KEY (task_id, category_id),
    CONSTRAINT fk_task_categories_task
        FOREIGN KEY (task_id) REFERENCES public.tasks(id),
    CONSTRAINT fk_task_categories_category
        FOREIGN KEY (category_id) REFERENCES public.categories(id)
);
